// Optional: npm install playwright, then start python tests/serve_fixture.py.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.MG_TEST_CHROME||undefined});
  const context=await browser.newContext({viewport:{width:1376,height:1000},locale:'cs-CZ'});
  const page=await context.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('console',message=>{if(message.text().includes('Content Security Policy')) errors.push(message.text());});
  try {
    await page.goto('http://127.0.0.1:'+(process.env.MG_TEST_PORT||'18787')+'/');
    await page.locator('#login').waitFor({state:'visible'});
    await page.locator('#login-form input[name=password]').fill('test-only-password-83942');
    await page.locator('#login-form button').click();
    await page.locator('#application').waitFor({state:'visible'});
    await page.locator('#queue-list .job').waitFor();
    await page.locator('#download-form textarea').fill('https://www.youtube.com/playlist?list=PLabcdefgh');
    await page.locator('#preview-button').click();
    await page.locator('#preview-dialog').waitFor({state:'visible'});
    assert.equal(await page.locator('#preview-list input').count(),2);
    await page.locator('#select-none').click();
    await page.locator('#preview-list input').nth(1).check();
    await page.locator('#apply-selection').click();
    await page.locator('#download-form .primary').click();
    await page.waitForFunction(()=>document.querySelectorAll('#queue-list .job').length===2);
    const state=await page.evaluate(()=>fetch('/api/state').then(r=>r.json()));
    const selected=state.jobs.find(j=>j.title==='Test album');
    assert.equal(selected.items.length,1);assert.equal(selected.items[0].position,2);
    await page.locator('#download-form [name=mode]').selectOption('video');
    assert.equal(await page.locator('#download-form [name=quality]').inputValue(),'1080');
    await page.locator('#download-form [name=mode]').selectOption('audio');
    await page.locator('#download-form .browse-folder').click();
    await page.locator('#folder-list button').filter({hasText:'Music'}).click();
    await page.locator('#use-folder').click();
    assert.equal(await page.locator('#download-form [name=folder]').inputValue(),'Music');
    await page.locator('[data-tab=sources]').click();
    await page.locator('#add-source').click();
    await page.locator('#source-form [name=name]').fill('Oblíbený kanál');
    await page.locator('#source-form [name=url]').fill('https://www.youtube.com/@TestChannel');
    await page.locator('#source-form .primary').click();
    await page.locator('#source-list .job').waitFor();
    assert.match(await page.locator('#source-list').innerText(),/Oblíbený kanál/);
    await page.locator('#toast').waitFor({state:'hidden'});
    await page.screenshot({path:path.join(process.env.MG_TEST_SCREENSHOTS||'.','mediagrabber-nas-sources.png'),fullPage:true});
    await page.locator('[data-tab=settings]').click();
    await page.locator('#settings-form [name=rate_kib]').fill('256');
    await page.locator('#settings-form .primary').click();
    await page.waitForFunction(async()=>(await fetch('/api/state').then(r=>r.json())).settings.rate_kib===256);
    const backup=await page.evaluate(()=>fetch('/api/backup').then(r=>r.json()));
    assert.equal(backup.jobs.length,2);assert.equal(backup.sources.length,1);assert(!JSON.stringify(backup).includes('test-only-password'));
    page.once('dialog',d=>d.accept());
    await page.locator('#backup-file').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
    await page.waitForFunction(async()=>(await fetch('/api/state').then(r=>r.json())).settings.queue_paused===true);
    await page.locator('#language').selectOption('en');
    assert.equal(await page.locator('[data-tab=sources]').innerText(),'Watched sources');
    await page.locator('#language').selectOption('cs');
    assert.equal(await page.locator('#pause-all').innerText(),'Obnovit frontu');
    await page.locator('[data-tab=queue]').click();
    await page.locator('#toast').waitFor({state:'hidden'});
    await page.screenshot({path:path.join(process.env.MG_TEST_SCREENSHOTS||'.','mediagrabber-nas-queue.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(process.env.MG_TEST_SCREENSHOTS||'.','mediagrabber-nas-mobile.png'),fullPage:true});
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
    assert.equal(overflow,false,'mobile page overflows horizontally');
    await page.locator('#help-button').click();
    await page.locator('#help-dialog').waitFor({state:'visible'});
    await page.locator('#help-dialog .dialog-footer button').click();
    await page.locator('#logout').click();
    await page.locator('#login').waitFor({state:'visible'});
    assert.deepEqual(errors,[]);
    console.log('PASS: login, frozen selection, profiles, folder browser, source, settings, backup/import, CZ/EN, mobile, help, logout; no JS/CSP errors');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
